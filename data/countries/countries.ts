// Helper: Derived country location names
export const COUNTRY_NAMES: string[] = countries.map((c) => c.name);

// Helper: Derived unique currencies with code, label, name, and symbol
export interface CurrencyOption {
  value: string;
  label: string;
  code: string;
  name: string;
  symbol: string;
}

// Extract distinct currencies preserving primary choices first
const priorityCurrencyCodes = ["PKR", "USD", "EUR", "GBP", "CAD", "AUD", "AED", "SAR", "INR"];

const currencyMap = new Map<string, CurrencyOption>();

// First add priority currencies
for (const code of priorityCurrencyCodes) {
  const match = countries.find((c) => c.currency === code);
  if (match && !currencyMap.has(code)) {
    currencyMap.set(code, {
      value: match.currency,
      code: match.currency,
      name: match.currency_name,
      symbol: match.currency_symbol,
      label: `${match.currency} - ${match.currency_name}`,
    });
  }
}

// Then add all other currencies
for (const country of countries) {
  if (!currencyMap.has(country.currency)) {
    currencyMap.set(country.currency, {
      value: country.currency,
      code: country.currency,
      name: country.currency_name,
      symbol: country.currency_symbol,
      label: `${country.currency} - ${country.currency_name}`,
    });
  }
}

export const UNIQUE_CURRENCIES: CurrencyOption[] = Array.from(currencyMap.values());

// Helper functions
export const getCountryByName = (name: string): Country | undefined =>
  countries.find((c) => c.name.toLowerCase() === name.toLowerCase());

export const getCountryByCode = (code: string): Country | undefined =>
  countries.find((c) => c.code.toLowerCase() === code.toLowerCase());

export const getCurrencyByCountry = (countryName: string): string => {
  const match = getCountryByName(countryName);
  return match ? match.currency : "PKR";
};

export const getCurrencySymbol = (currencyCode?: string): string => {
  if (!currencyCode) return "₨";
  const code = currencyCode.trim().toUpperCase();
  const option = UNIQUE_CURRENCIES.find(
    (c) => c.code.toUpperCase() === code || c.value.toUpperCase() === code,
  );
  if (option?.symbol) return option.symbol;
  const match = countries.find((c) => c.currency.toUpperCase() === code);
  return match?.currency_symbol || currencyCode;
};

export const getCurrencySymbolByCode = getCurrencySymbol;
